#!/usr/bin/env python3
"""Prepare the supplied SVAROG OBJ without changing its UVs or proportions.

Run before Godot import and tools/art/build_tank_sprites.gd. The model is Y-up,
faces +Z, and has its turret centred at (0, *, 0.7). Game models face +X.
The complete vehicle fits within the existing 3 m footprint at 32 pixels/metre.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FOLDER = ROOT / "assets/models/tank"
SOURCE = FOLDER / "source/SVAROG.obj"
TURRET_OBJECTS = {"Cylinder", "Cylinder.001", "Cube.007"}
PAINT_OBJECTS = TURRET_OBJECTS | {"Cube", "Cube.001", "Cube.006"}
SOURCE_VERTICES = [tuple(map(float, line.split()[1:4]))
                   for line in SOURCE.read_text().splitlines() if line.startswith("v ")]
Z_MIN = min(v[2] for v in SOURCE_VERTICES)
Z_MAX = max(v[2] for v in SOURCE_VERTICES)
SCALE = 2.875 / (Z_MAX - Z_MIN)
CENTER_Z = (Z_MAX + Z_MIN) / 2.0
TURRET_Z = 0.7


def build():
    common = []
    faces = {"hull": [], "turret": []}
    part = "hull"
    painted = False
    for line in SOURCE.read_text().splitlines():
        kind, _, value = line.partition(" ")
        if kind == "o":
            part = "turret" if value in TURRET_OBJECTS else "hull"
            painted = value in PAINT_OBJECTS
            faces[part].append(line)
        elif kind == "v":
            x, y, z = map(float, value.split())
            # Rotate +Z to +X, raise the track base to the ground, and centre.
            common.append("v %.9f %.9f %.9f" % ((z - CENTER_Z) * SCALE,
                          (y + 1.0) * SCALE, -x * SCALE))
        elif kind == "vn":
            x, y, z = map(float, value.split())
            common.append("vn %.9f %.9f %.9f" % (z, y, -x))
        elif kind == "vt":
            common.append(line)
        elif kind == "usemtl":
            faces[part].append("usemtl TeamPaint" if painted else line)
        elif kind in {"f", "s"}:
            faces[part].append(line)
    # Retain global OBJ indices: both outputs carry the unchanged attribute tables.
    for name, records in faces.items():
        out = ["# Generated by tools/art/build_tank_meshes.py", "mtllib tank.mtl"]
        out.extend(common)
        out.extend(records)
        (FOLDER / (name + ".obj")).write_text("\n".join(out) + "\n")
    material = "Kd 1 1 1\nKs 0 0 0\nNs 0\nd 1\nillum 2\nmap_Kd source/albedo.jpg\n"
    (FOLDER / "tank.mtl").write_text(
        "# Generated texture bindings; TeamPaint marks armour, not tracks.\n"
        + "newmtl Material.001\n" + material + "\nnewmtl TeamPaint\n" + material)
    print("SVAROG: hull and turret written; turret pivot X = %.9f" %
          ((TURRET_Z - CENTER_Z) * SCALE))


if __name__ == "__main__":
    build()
